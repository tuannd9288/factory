// A module is what the factory holds only for the repositories that turn it on, as a pack is what it holds only for one
// way of working: modules/<name>/kit/ holds the files it adds, at repository paths, and modules/<name>/test/ the
// factory's tests for it. A repository names its modules in .gate/modules, one name a line, sorted; the file is tier 3,
// and absent means none. bin/onboard and bin/kit-update write it as they write .gate/pack, so bin/kit-evidence can
// prove it. A module's files are copied into a repository only when it names the module; they may not be at a kit
// path, at another module's path, or at a file onboard and kit-update generate.
//   node bin/lib/module.mjs check <factory> <name>...   the working tree's modules exist and collide with nothing
//   node bin/lib/module.mjs files <factory> <name>...   "<path>\t<module>" for every file they lay, sorted
//   node bin/lib/module.mjs names <file>                the names a .gate/modules holds, one a line
//   node bin/lib/module.mjs update <file> <add> <remove>   the names left on (comma lists), one a line
// On an error it prints the message to stderr and exits 2.
import { readFileSync, readdirSync, realpathSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tree } from './evidence.mjs';
import { NAME } from './pack.mjs';

export const MODULES_FILE = '.gate/modules';
const GENERATED = ['.gate/pack', '.gate/kit-files', MODULES_FILE];

/** The names a .gate/modules holds: text is null or empty for none; else one sorted, unique name a line, newline last. */
export function parseModules(text) {
  if (text === null || text === '') return [];
  if (!text.endsWith('\n')) throw new Error(`${MODULES_FILE}: not a list of names, one a line, with a newline last`);
  const names = text.slice(0, -1).split('\n');
  names.forEach((name, i) => {
    if (!NAME.test(name) || name === 'none') throw new Error(`${MODULES_FILE}: ${JSON.stringify(name)} is not a module name (lowercase letters, digits and hyphens)`);
    if (i > 0 && names[i - 1] >= name) throw new Error(`${MODULES_FILE}: ${name} is out of order or listed twice; names are sorted, one each`);
  });
  return names;
}

/** The modules left on after --module and --no-module: the current ones, less `remove`, with `add`, sorted. */
export function updateModules(current, add, remove) {
  const both = add.filter((name) => remove.includes(name));
  if (both.length) throw new Error(`--module and --no-module both name ${both[0]}`);
  return [...new Set([...current.filter((name) => !remove.includes(name)), ...add])].sort();
}

/** The modules a base's .gate/modules text names (null: none). A text that does not parse names none; evidence and kit-update
 * judge the file itself. */
export function baseModules(text) {
  try {
    return parseModules(text);
  } catch {
    return [];
  }
}

/** The files, path → { mode, oid, src, module }, of the modules the base had on that `names` leaves out. Throws when the
 * base names a module the factory commit lacks: then nobody can say which files go, and the run must stop. */
export function offFiles(factory, fac, baseNames, names) {
  const off = baseNames.filter((name) => !names.includes(name));
  if (!off.length) return new Map();
  try {
    return new Map([...mergedTree(factory, fac, off)].filter(([, e]) => e.module));
  } catch (error) {
    throw new Error(`the base's ${MODULES_FILE}: ${error.message}`);
  }
}

/** The modules a factory commit holds: the folders of modules/. */
export function moduleNames(factory, fac) {
  return [...new Set([...tree(factory, fac, 'modules/').keys()].map((p) => p.split('/')[0]))].sort();
}

/** Who lays each path: null for the kit, else a module's name; throws on a module that is unknown or lays a path twice. */
function owners(kit, have, byModule, where) {
  const owner = new Map([...kit].map((path) => [path, null]));
  for (const [name, paths] of [...byModule].sort(([a], [b]) => (a < b ? -1 : 1))) {
    if (!NAME.test(String(name)) || !have.includes(name)) throw new Error(`no module ${name} in ${where}; there are: ${have.join(', ')}`);
    for (const path of paths) {
      if (GENERATED.includes(path)) throw new Error(`${path}: module ${name} lays it, but it is generated by onboard and kit-update`);
      if (owner.has(path)) throw new Error(`${path}: module ${name} lays it, and ${owner.get(path) === null ? 'the kit' : `module ${owner.get(path)}`} already does`);
      owner.set(path, name);
    }
  }
  return owner;
}

/** The kit's files and those of each named module, at a factory commit: path → { mode, oid, src, module }. `src` is the
 * path in the factory (kit/<path> or modules/<name>/kit/<path>), where the file's history lives; `module` is absent for
 * the kit's own. */
export function mergedTree(factory, fac, names) {
  const kit = tree(factory, fac, 'kit/');
  const mine = [...new Set(names)].sort().map((name) => [name, tree(factory, fac, `modules/${name}/kit/`)]);
  const owner = owners(kit.keys(), moduleNames(factory, fac), mine.map(([name, files]) => [name, files.keys()]), `${fac.slice(0, 12)}/modules`);
  const out = new Map([...kit].map(([path, e]) => [path, { ...e, src: `kit/${path}` }]));
  for (const [name, files] of mine) for (const [path, e] of files) out.set(path, { ...e, src: `modules/${name}/kit/${path}`, module: owner.get(path) });
  return out;
}

const walk = (dir) => {
  try {
    return readdirSync(dir, { recursive: true, withFileTypes: true })
      .filter((e) => !e.isDirectory() && e.name !== '.DS_Store')
      .map((e) => join(e.parentPath, e.name).slice(dir.length + 1))
      .sort();
  } catch {
    return [];
  }
};

/** The working tree's version of mergedTree: [path, module] for each file the named modules lay, sorted by path. */
function filesOf(factory, names) {
  const dir = join(factory, 'modules');
  let have = [];
  try {
    have = readdirSync(dir, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort();
  } catch {}
  const mine = [...new Set(names)].sort().map((name) => [name, walk(join(dir, String(name), 'kit'))]);
  const owner = owners(walk(join(factory, 'kit')), have, mine, join(factory, 'modules'));
  return [...owner].filter(([, name]) => name !== null).sort(([a], [b]) => (a < b ? -1 : 1));
}

function main([verb, arg, ...names]) {
  if (verb === 'names' && arg) {
    for (const name of parseModules(readFileSync(arg, 'utf8'))) console.log(name);
  } else if (verb === 'update' && arg && names.length === 2) {
    const list = (csv) => csv.split(',').filter(Boolean);
    for (const name of updateModules(parseModules(readFileSync(arg, 'utf8')), list(names[0]), list(names[1]))) console.log(name);
  } else if (['check', 'files'].includes(verb) && arg) {
    const files = filesOf(arg, names);
    if (verb === 'files') for (const [path, name] of files) console.log(`${path}\t${name}`);
  } else throw new Error('usage: node bin/lib/module.mjs check|files <factory> <name>... | names <file> | update <file> <add> <remove>');
}

// Node loads the main module by its real path: started through a symlinked directory, argv[1] still names this file.
if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 2;
  }
}
